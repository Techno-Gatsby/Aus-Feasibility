// node tools/mktrk.mjs <Trackers.xlsx> – writes src/00-trklayout.js: the "Tax Invoice Tracker" groups, rows and entries
// shipped with the tracker (Billing → 3 Tracker). Uses the same reader as "Import tracker Excel…" in the app.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../tests/', import.meta.url));
const XLSX = require('xlsx');
const src = readFileSync(new URL('../src/06b-tracker.js', import.meta.url), 'utf8');
const trkParse = new Function(src.match(/function trkParse\(rows\)[\s\S]*?\n}\n/)[0] + 'return trkParse;')();
const wb = XLSX.read(readFileSync(process.argv[2]), { type: 'buffer' });
const rows = XLSX.utils.sheet_to_json(wb.Sheets['Tax Invoice Tracker'], { header: 1, raw: true, defval: null, blankrows: true });
const t = trkParse(rows);
writeFileSync(new URL('../src/00-trklayout.js', import.meta.url), `/* Tax Invoice Tracker layout – generated by tools/mktrk.mjs from Trackers.xlsx */\nconst TRK0 = ${JSON.stringify(t)};\n`);
console.log(t.groups.map(g => `${g.name}: ${g.rows.length}`).join(' · '), '·', t.vals.length, 'entries');
